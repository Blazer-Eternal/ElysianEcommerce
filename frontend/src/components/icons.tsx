import type { ReactNode, SVGProps } from "react";

/**
 * Shared stroke icon set (Feather-style geometry, 24x24 grid, currentColor).
 * Single source of truth for every icon in the app — do not inline new SVGs
 * in feature files; add an icon here instead.
 */

export interface IconProps extends SVGProps<SVGSVGElement> {
  size?: number;
}

interface IconOptions {
  /** Default rendered size in px (default 24). */
  defaultSize?: number;
  /** Default stroke width (default 2). */
  defaultStroke?: number;
  /** Render as a filled glyph instead of a stroke outline. */
  filled?: boolean;
}

const makeIcon = (paths: ReactNode, displayName: string, options: IconOptions = {}) => {
  const { defaultSize = 24, defaultStroke = 2, filled = false } = options;

  const Icon = ({ size = defaultSize, strokeWidth, ...rest }: IconProps) => (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill={filled ? "currentColor" : "none"}
      stroke={filled ? "none" : "currentColor"}
      strokeWidth={strokeWidth ?? defaultStroke}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...rest}
    >
      {paths}
    </svg>
  );

  Icon.displayName = displayName;
  return Icon;
};

